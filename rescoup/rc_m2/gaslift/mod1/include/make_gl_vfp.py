#!/usr/bin/env python3
"""Add a lift-gas (ALQ) axis to the single-ALQ PROSPER VFPPROD tables of mod1.

Lift gas is treated as extra gas in the tubing: for an ALQ value (lift gas
rate, SM3/DAY) the BHP is taken from the original table at the effective GOR

    GOR_eff = GOR + ALQ / (Q_liq * max(1 - WCT, 0.05))

interpolated linearly in the original GOR axis (clamped at its end points).
The ALQ=0 slice is therefore identical to the original table, and the gain
from lift gas diminishes (and eventually reverses through friction) as in the
original high-GOR rows.

Usage (from this directory):  python3 make_gl_vfp.py ../../../common/mod1/B2H.Ecl
    ../../../common/mod1/D1CH.Ecl ../../../common/mod1/D2H.Ecl
writes B2H_GL.Ecl, D1CH_GL.Ecl, D2H_GL.Ecl here.
"""
import os
import re
import sys

import numpy as np

ALQ = [0.0, 25000.0, 50000.0, 100000.0, 200000.0, 400000.0]


def records(text):
    """Split the VFPPROD keyword body (comments removed) into '/'-terminated records."""
    body = "\n".join(line.split("--")[0] for line in text.splitlines())
    body = body[body.index("VFPPROD") + len("VFPPROD"):]
    return [r.split() for r in body.split("/")]


def convert(src, dst):
    recs = records(open(src).read())
    head = recs[0]
    flo, thp, wfr, gfr = (np.array(r, float) for r in recs[1:5])
    nq, nt, nw, ng = len(flo), len(thp), len(wfr), len(gfr)
    bhp = np.zeros((nt, nw, ng, nq))
    for r in recs[6:6 + nt * nw * ng]:
        it, iw, ig, ia = (int(v) for v in r[:4])
        assert ia == 1
        bhp[it - 1, iw - 1, ig - 1] = np.array(r[4:], float)

    def fmt(vals, per=5):
        return "\n".join(" " + " ".join(f"{v:9.2f}" for v in vals[i:i + per])
                         for i in range(0, len(vals), per))

    out = [f"-- Generated by make_gl_vfp.py from {os.path.basename(src)}: lift-gas ALQ axis added.",
           "-- ALQ=0 slice is identical to the original table.", "",
           "VFPPROD", "",
           "-- Table  Datum Depth  Rate Type  WFR Type  GFR Type  THP Type  ALQ Type  UNITS  TAB Type",
           f"   {head[0]}   {head[1]}   {head[2]}   {head[3]}   {head[4]}"
           "   'THP'   'GRAT'   'METRIC'   'BHP' /", "",
           "-- 'LIQ' units - SM3/DAY", fmt(flo) + " /", "",
           "-- 'THP' units - BARSA", fmt(thp) + " /", "",
           "-- 'WCT' units - FRACTION", fmt(wfr) + " /", "",
           "-- 'GOR' units - SM3/SM3", fmt(gfr) + " /", "",
           "-- 'ALQ' units - SM3/DAY (lift gas rate)", fmt(ALQ) + " /", ""]
    for it in range(nt):
        for iw in range(nw):
            oil_frac = max(1.0 - wfr[iw], 0.05)
            for ig in range(ng):
                for ia, alq in enumerate(ALQ):
                    gor_eff = gfr[ig] + alq / (flo * oil_frac)
                    vals = [np.interp(gor_eff[iq], gfr, bhp[it, iw, :, iq])
                            for iq in range(nq)]
                    lines = fmt(vals).splitlines()
                    out.append(f" {it + 1:2d} {iw + 1:2d} {ig + 1:2d} {ia + 1:2d} "
                               + lines[0].strip())
                    out += ["              " + l.strip() for l in lines[1:]]
                    out.append("/")
    open(dst, "w").write("\n".join(out) + "\n")
    print(f"{src} -> {dst}: {nt}x{nw}x{ng}x{len(ALQ)} records")


if __name__ == "__main__":
    for f in sys.argv[1:]:
        convert(f, re.sub(r"\.Ecl$", "_GL.Ecl", os.path.basename(f)))
