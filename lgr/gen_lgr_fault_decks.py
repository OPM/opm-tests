#!/usr/bin/env python3
"""Generate the lgr-fault decks: a 12x10x6 corner-point grid with one I-fault
(between cells I=6 and I=7) of adjustable throw, and CARFIN boxes at the fault.

Run from this directory: python3 gen_lgr_fault_decks.py
"""
from pathlib import Path

NX, NY, NZ = 12, 10, 6
DXY = 300.0       # ft
DZ = 20.0         # ft
TOP = 8325.0
DIP = 0.02        # ft per ft in x
FAULT_I = 6       # 0-based first cell on the thrown side (I=7 in the deck)

HERE = Path(__file__).resolve().parent

HEADER = """\
-- This reservoir simulation deck is made available under the Open Database
-- License: http://opendatacommons.org/licenses/odbl/1.0/. Any rights in
-- individual contents of the database are licensed under the Database Contents
-- License: http://opendatacommons.org/licenses/dbcl/1.0/
-- Copyright (C) 2026 Equinor
-- Fluid and rock data from opm-tests/lgr/SPE1CASE1_CARFIN1.DATA.
-- Generated by gen_lgr_fault_decks.py; edit the generator, not this file.
"""


def node_depth(x, k, thin):
    """Depth of the layer-k node row at pillar x; `thin` = (k_layer, dz) override."""
    d = TOP + DIP * x
    for kk in range(k):
        d += thin[1] if thin and kk == thin[0] else DZ
    return d


def grid_text(throw, thin_cols=None, thin=None):
    """COORD + ZCORN. thin: (layer, dz) applied to cells with i in thin_cols."""
    out = ["COORD"]
    for j in range(NY + 1):
        for i in range(NX + 1):
            x, y = i * DXY, j * DXY
            out.append(f"  {x:.1f} {y:.1f} 8000.0 {x:.1f} {y:.1f} 8800.0")
    out.append("/")
    z = []
    for k in range(NZ):
        for side in (0, 1):            # top, bottom of layer k
            for j in range(NY):
                for _ in (0, 1):       # y-, y+ row
                    for i in range(NX):
                        shift = throw if i >= FAULT_I else 0.0
                        for xi in (i, i + 1):
                            # thin_cols are pillar indices; thinning stays on the low side
                            th = thin if (thin and i < FAULT_I and xi in thin_cols) else None
                            z.append(node_depth(xi * DXY, k + side, th) + shift)
    out.append("ZCORN")
    for n in range(0, len(z), 8):
        out.append("  " + " ".join(f"{v:.3f}" for v in z[n:n + 8]))
    out.append("/")
    return "\n".join(out) + "\n"


def actnum_text(inactive):
    vals = []
    for k in range(NZ):
        for j in range(NY):
            for i in range(NX):
                vals.append("0" if (i + 1, j + 1, k + 1) in inactive else "1")
    lines = ["ACTNUM"] + ["  " + " ".join(vals[n:n + 24]) for n in range(0, len(vals), 24)]
    return "\n".join(lines) + "\n/\n"


PROPS = (HERE / "LGRF_PROPS.INC").name


def deck(name, purpose, carfin, throw, extra_grid="", runspec_extra="",
         thin_cols=None, thin=None, inactive=None):
    grid_inc = f"{name}.GRDECL"
    g = grid_text(throw, thin_cols, thin)
    if inactive:
        g += actnum_text(inactive)
    (HERE / "include" / grid_inc).write_text(HEADER + g)
    text = f"""{HEADER}-- {purpose}
-- Fault between I=6 and I=7, throw {throw:g} ft (cells I>=7 are deeper).

RUNSPEC
TITLE
  {name}
DIMENS
  {NX} {NY} {NZ} /
EQLDIMS
/
TABDIMS
/
OIL
GAS
WATER
DISGAS
FIELD
START
  1 'JAN' 2015 /
WELLDIMS
  2 6 1 2 /
UNIFOUT
{runspec_extra}
GRID
{carfin}
INIT
INCLUDE
  'include/{grid_inc}' /
{extra_grid}
PORO
  {NX*NY*NZ}*0.3 /
PERMX
  {NX*NY*2}*500 {NX*NY*2}*50 {NX*NY*2}*200 /
COPY
  PERMX PERMY /
  PERMX PERMZ /
/
MULTIPLY
  PERMZ 0.1 /
/

INCLUDE
  'include/{PROPS}' /

SCHEDULE
RPTRST
  'BASIC=2' /
DRSDT
  0 /
WELSPECS
  'PROD' 'G1' 12 10 1* 'OIL' /
  'INJ'  'G1'  1  1 1* 'GAS' /
/
COMPDAT
  'PROD' 12 10 4 6 'OPEN' 1* 1* 0.5 /
  'INJ'   1  1 1 2 'OPEN' 1* 1* 0.5 /
/
WCONPROD
  'PROD' 'OPEN' 'ORAT' 8000 4* 1000 /
/
WCONINJE
  'INJ' 'GAS' 'OPEN' 'RATE' 30000 1* 9014 /
/
TSTEP
  24*15 /
END
"""
    (HERE / f"{name}.DATA").write_text(text)


def carfin(*boxes):
    """boxes: (name, i1,i2,j1,j2,k1,k2, nx,ny,nz[, parent])"""
    s = []
    for b in boxes:
        parent = f" 1* '{b[10]}'" if len(b) > 10 else ""
        s.append("CARFIN\n  '%s' %d %d %d %d %d %d %d %d %d%s /\nENDFIN" % (*b[:10], parent))
    return "\n".join(s)


DECKS = []


def add(name, purpose, **kw):
    DECKS.append((name, purpose))
    deck(name, purpose, **kw)


def main():
    (HERE / "include").mkdir(exist_ok=True)

    # 01: one box with its I+ side on the fault.
    b01 = ("B", 4, 6, 4, 6, 2, 4, 9, 9, 6)
    for t, tag in ((0, "T00"), (10, "T05"), (30, "T15"), (60, "T30")):
        add(f"LGR-FAULT-01_{tag}", "Box 3x3x2 with its I+ side on the fault",
            carfin=carfin(b01), throw=t)
    add("LGR-FAULT-01B_T15", "Box 3x3x1 (no K refinement) with its I+ side on the fault",
        carfin=carfin(("B", 4, 6, 4, 6, 2, 4, 9, 9, 3)), throw=30)

    # 02: two boxes touching across the fault.
    for t, tag in ((0, "T00"), (10, "T05"), (30, "T15"), (60, "T30")):
        add(f"LGR-FAULT-02_{tag}", "Two boxes 3x3x1 touching across the fault",
            carfin=carfin(("L", 4, 6, 4, 6, 2, 4, 9, 9, 3),
                          ("R", 7, 9, 4, 6, 2, 4, 9, 9, 3)), throw=t)
    add("LGR-FAULT-02C_T15", "Boxes touching across the fault, factors 3 and 6 (compatible)",
        carfin=carfin(("L", 4, 6, 4, 6, 2, 4, 9, 9, 3),
                      ("R", 7, 9, 4, 6, 2, 4, 18, 18, 3)), throw=30)

    # 03: two boxes along the fault on the low side, different factors.
    add("LGR-FAULT-03_T15", "Boxes along the fault, same side, factors 3 and 6 sharing a J face",
        carfin=carfin(("A", 4, 6, 2, 4, 2, 4, 9, 9, 3),
                      ("C", 4, 6, 5, 7, 2, 4, 18, 18, 3)), throw=30)

    # 04: nested box strictly inside a box on the fault (a nested box may not touch its parent's boundary).
    add("LGR-FAULT-04_T15", "Nested box (factor 2) inside a 4x4x3 box on the fault, one parent cell from the fault side",
        carfin=carfin(("P", 4, 6, 4, 6, 2, 4, 12, 12, 9),
                      ("N", 7, 11, 3, 10, 2, 8, 10, 16, 14, "P")), throw=30)

    # 05: thin layer 3 in the two columns next to the fault; MINPV removes it.
    add("LGR-FAULT-05_T15", "Box on the fault containing a MINPV-removed thin layer, PINCH on",
        carfin=carfin(b01), throw=30, thin_cols={5, 6}, thin=(2, 0.5),
        extra_grid="MINPV\n  3000 /\nPINCH\n  1* 'GAP' /\n")

    # 06: throw taller than the box; far-side neighbours partly inactive.
    inactive = {(7, j, k) for j in range(4, 7) for k in (1, 2)}
    add("LGR-FAULT-06_T30", "Throw (60 ft) taller than the 2-layer box; far-side hosts inactive",
        carfin=carfin(("B", 4, 6, 4, 6, 2, 3, 9, 9, 4)), throw=60, inactive=inactive)

    print("\n".join(f"{n}: {p}" for n, p in DECKS))


if __name__ == "__main__":
    main()
